// generate-history-data — bundle the finished history with the app.
//
// The auction drafts and the game log are DONE. 2008-2025 will never change,
// and together they are 7,546 rows that gzip to about 70KB — smaller than
// the History page's own JavaScript. Fetching them from Firestore on every
// visit buys nothing and costs a round trip, a reads bill, and a dependency
// on someone having remembered to run the import.
//
// So they ship as lazy-loaded chunks instead, and those two tabs work on a
// fresh deploy whether or not Firestore has ever been seeded.
//
// Player scores stay in Firestore: 36,000 rows is a different question, and
// that tab is season-scoped for exactly that reason.
//
// Rows are arrays, not objects, with the column order documented in the
// generated file. Object keys would repeat 4,066 times and triple the size
// for no benefit — the category's toRows() names them on the way in.
//
//   node web/scripts/generate-history-data.mjs [--write]
import { readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const CSV = join(ROOT, 'data/iffl_fantasy_history_2008-2025.csv')
const IDENTITY = join(ROOT, 'data/espn-team-identity-map.json')

const lines = readFileSync(CSV, 'utf8').split(/\r?\n/).filter(Boolean)
const head = lines[0].split(',')
const ix = Object.fromEntries(head.map((h, i) => [h, i]))
const owners = JSON.parse(readFileSync(IDENTITY, 'utf8')).seasons

// ESPN team names are what a manager called their team that season and they
// rename constantly; TeamId is the stable franchise slot. Resolve to the
// league's master names here, once, so nothing downstream has to.
const owner = (season, teamId) => owners[season]?.[teamId] ?? ''

const num = (v) => {
  const n = Number(v)
  return Number.isFinite(n) ? n : null
}

const auction = []
const games = []
for (const line of lines.slice(1)) {
  const c = line.split(',')
  const type = c[ix.RecordType]
  const season = c[ix.Season]
  if (type === 'DraftPick') {
    auction.push([
      Number(season), owner(season, c[ix.TeamId]), c[ix.Player], c[ix.Position],
      c[ix.ProTeam], num(c[ix.AuctionPrice]) ?? 0, num(c[ix.OverallPick]) ?? 0,
      c[ix.Keeper] === 'Y' ? 1 : 0,
    ])
  } else if (type === 'TeamWeek') {
    games.push([
      Number(season), num(c[ix.Week]), owner(season, c[ix.TeamId]),
      num(c[ix.TeamScore]), owner(season, c[ix.OpponentTeamId]), num(c[ix.OpponentScore]),
      // ESPN's Winner column disagrees with its own scores on 7 playoff
      // rows. Keep ESPN's verdict — it is what the standings were built
      // from — and let anything margin-based derive W/L from the scores.
      c[ix.Winner] === 'W' ? 'W' : c[ix.Winner] === 'L' ? 'L' : (c[ix.Winner] || ''),
      num(c[ix.Margin]), num(c[ix.TeamBenchPoints]),
    ])
  }
}

const files = [
  {
    path: 'web/src/data/auctionHistory.js',
    name: 'auctionHistory',
    cols: 'season, owner, player, position, proTeam, price, overallPick, keeper(0|1)',
    note: 'Every auction pick 2008-2025. 228 a season (2008 is 190 — the league had 10 teams).',
    rows: auction,
  },
  {
    path: 'web/src/data/gamesHistory.js',
    name: 'gamesHistory',
    cols: 'season, week, team, points, opponent, oppPoints, result, margin, benchPoints',
    note: "Every game 2008-2025, one row per team per game, playoffs included.",
    rows: games,
  },
]

for (const f of files) {
  const js = `// ${f.note}
// Generated by web/scripts/generate-history-data.mjs — do not hand-edit.
//
// Rows are arrays, not objects, in this column order:
//   ${f.cols}
// Object keys would repeat ${f.rows.length.toLocaleString()} times and triple the file for no
// benefit; services/historyCategories.js names them on the way in.
export const ${f.name} = ${JSON.stringify(f.rows)}
`
  console.log(`${f.name.padEnd(16)} ${String(f.rows.length).padStart(5)} rows  ` +
    `${(js.length / 1024).toFixed(0)}KB raw  ${(gzipSync(js).length / 1024).toFixed(0)}KB gzipped`)
  if (process.argv.includes('--write')) {
    writeFileSync(join(ROOT, f.path), js)
    console.log(`                 wrote ${f.path}`)
  }
}
