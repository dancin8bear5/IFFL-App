// generate-trades-history — data/trades-2022-2024.csv -> the app's data file.
//
// The CSV is one row per asset that moved. The app wants whole trades, in
// the same shape as web/src/data/trades2026.js: each side and what it
// RECEIVED, which is how the league's own sheet has always recorded them.
// Keeping that shape means seedHistoricalTrades() can push these to
// Firestore later without a second translation, and the flip to the app's
// assetsFromProposer / assetsFromReceiver still happens in exactly one place.
//
//   node web/scripts/generate-trades-history.mjs [--write]
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const SRC = join(ROOT, 'data/trades-2022-2024.csv')
const OUT = join(ROOT, 'web/src/data/tradesHistory.js')

const lines = readFileSync(SRC, 'utf8').split(/\r?\n/).filter(Boolean)
const head = lines[0].split(',')
const rows = lines.slice(1).map((l) => Object.fromEntries(l.split(',').map((v, i) => [head[i], v])))

// Group the movements back into trades, preserving sheet order.
const byTrade = new Map()
for (const r of rows) {
  if (!byTrade.has(r.trade_id)) {
    byTrade.set(r.trade_id, { id: r.trade_id, season: Number(r.season), date: r.date, sides: new Map() })
  }
  const t = byTrade.get(r.trade_id)
  if (!t.sides.has(r.to_team)) t.sides.set(r.to_team, [])
  t.sides.get(r.to_team).push(r.asset)
}

const bySeason = {}
let skipped = 0
for (const t of byTrade.values()) {
  const sides = [...t.sides.entries()]
  // Every trade in this data is two-sided. A third party would mean the
  // sheet recorded something this shape can't hold, so say so rather than
  // silently dropping the extra team.
  if (sides.length !== 2) { skipped += 1; console.warn(`skipped ${t.id}: ${sides.length} sides`); continue }
  const [[aTeam, aGot], [bTeam, bGot]] = sides
  ;(bySeason[t.season] ??= []).push({
    date: t.date,
    a: { team: aTeam, received: aGot },
    b: { team: bTeam, received: bGot },
  })
}

for (const s of Object.keys(bySeason)) {
  bySeason[s].sort((x, y) => (y.date ?? '').localeCompare(x.date ?? ''))  // newest first, like trades2026
}

const seasons = Object.keys(bySeason).map(Number).sort()
const total = seasons.reduce((a, s) => a + bySeason[s].length, 0)
console.log(`${total} trades across ${seasons.join(', ')}${skipped ? ` (${skipped} skipped)` : ''}`)
for (const s of seasons) console.log(`   ${s}: ${bySeason[s].length}`)

if (process.argv.includes('--write')) {
  const body = seasons.map((s) => {
    const rowsJs = bySeason[s].map((t) => `    ${JSON.stringify(t)},`).join('\n')
    return `  ${s}: [\n${rowsJs}\n  ],`
  }).join('\n')

  writeFileSync(OUT, `// Trade history 2022-2024, from the league's hand-kept workbook.
// Generated by web/scripts/generate-trades-history.mjs — do not hand-edit.
//
// Same shape as trades2026.js: each side and what it RECEIVED, which is the
// sheet's own convention and the opposite of the app's assetsFromProposer /
// assetsFromReceiver. The flip happens once, in seedHistoricalTrades().
//
// 2025 is missing because the league never kept a sheet for it.
export const tradesHistory = {
${body}
}

/** Every historical trade as one flat list, newest season first. */
export function allHistoricalTrades() {
  return Object.keys(tradesHistory)
    .map(Number)
    .sort((a, b) => b - a)
    .flatMap((season) => tradesHistory[season].map((t) => ({ ...t, season })))
}
`)
  console.log(`\nwrote ${OUT}`)
}
